/* =========================================================
   Static site generation for the event landing pages + sitemap.xml.
   Each page is rendered with React on the server (renderToString) into
   <slug>.html, so Google reads the full text; in the browser
   src/app/event.tsx hydrates the same markup.
   Run: npm run pages  (also runs automatically before every build)
   Content: src/data/pages.ts · prices, phone, address: src/data/site.ts
   ========================================================= */
import fs from "node:fs";
import path from "node:path";
import { renderToString } from "react-dom/server";
import { EVENT_PAGES } from "@/data/pages";
import { SITE } from "@/data/site";
import { EventPage } from "@/features/event/EventPage";
import { fillEventText } from "@/features/event/text";

const ROOT = path.resolve(__dirname, "..");
const BASE = SITE.siteUrl.replace(/\/?$/, "/");
const esc = (s: string) => s.replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]!);

// accessibility preferences before first paint (same snippet as every page)
const A11Y_BOOT = fs.readFileSync(path.join(ROOT, "index.html"), "utf8").match(/ {2}<script>\n {4}\/\* accessibility preferences[\s\S]*?<\/script>/)![0];

for (const P of EVENT_PAGES) {
  const url = `${BASE}${P.slug}.html`;
  const faqLd = {
    "@context": "https://schema.org",
    "@type": "FAQPage",
    mainEntity: P.faq.map((f) => ({ "@type": "Question", name: f.q, acceptedAnswer: { "@type": "Answer", text: fillEventText(f.a) } })),
  };
  const body = renderToString(<EventPage page={P} />);
  const html = `<!doctype html>
<html lang="he" dir="rtl">
<head>
  <meta charset="utf-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover" />
  <title>${esc(P.title)}</title>
  <meta name="description" content="${esc(P.desc)}" />
  <link rel="canonical" href="${url}" />
  <meta name="theme-color" content="#FFF7F8" />
  <meta property="og:title" content="${esc(P.h1)}" />
  <meta property="og:description" content="${esc(P.desc)}" />
  <meta property="og:type" content="website" />
  <meta property="og:locale" content="he_IL" />
  <meta property="og:image" content="${BASE}images/og.jpg" />
  <meta property="og:url" content="${url}" />
  <meta name="twitter:card" content="summary_large_image" />
  <link rel="icon" type="image/png" href="images/favicon.png" />
  <link rel="apple-touch-icon" href="images/favicon.png" />
  <link rel="preconnect" href="https://fonts.googleapis.com" />
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin />
  <link href="https://fonts.googleapis.com/css2?family=Heebo:wght@400;500;700;800&family=Suez+One&family=Playpen+Sans+Hebrew:wght@500;700&display=swap" rel="stylesheet" />
${A11Y_BOOT}
  <script type="application/ld+json">${JSON.stringify(faqLd)}</script>
</head>
<body class="ev-page">
  <!-- Generated by scripts/gen-pages.tsx from src/data/pages.ts. Don't edit here: edit the data and run npm run pages -->
  <div id="root" data-slug="${P.slug}">${body}</div>
  <script type="module" src="/src/app/event.tsx"></script>
</body>
</html>
`;
  fs.writeFileSync(path.join(ROOT, `${P.slug}.html`), html);
  console.log("page", `${P.slug}.html`);
}

// sitemap.xml
const today = new Date().toISOString().slice(0, 10);
const demos = fs.readdirSync(path.join(ROOT, "demos")).filter((f) => f.endsWith(".html") && f !== "preview.html");
const urls: [string, string][] = [
  ["", "1.0"],
  ["order.html", "0.9"],
  ...EVENT_PAGES.map((p): [string, string] => [`${p.slug}.html`, "0.8"]),
  ...demos.map((d): [string, string] => [`demos/${d}`, "0.5"]),
  ["terms.html", "0.2"],
  ["privacy.html", "0.2"],
  ["negishut.html", "0.2"],
];
fs.writeFileSync(
  path.join(ROOT, "public/sitemap.xml"),
  `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n` +
    urls.map(([u, pr]) => `  <url><loc>${BASE}${u}</loc><lastmod>${today}</lastmod><priority>${pr}</priority></url>`).join("\n") +
    `\n</urlset>\n`,
);
console.log("sitemap.xml:", urls.length, "urls");
